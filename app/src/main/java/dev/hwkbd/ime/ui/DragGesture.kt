package dev.hwkbd.ime.ui

/**
 * 拖动手势的**共用换算**:死区 → 跟手 → 触发阈值 → 松手补完/回退。
 *
 * 2026-09-29 用户定案「候选词翻页、L5 翻页和飞字的手感对齐,都支持死区、跟手动画和触发阈值」——
 * 三处手势此前各写一套:候选行翻页是 24dp 抬手判据(不跟手)、L5 翻页是 8dp 死区 + 36dp 提交
 * (不跟手)、飞字是死区 = 阈值 1/4(跟手)。现在统一到同一份数学,三处只差**阈值取值**与**轴向**。
 *
 * ## 关键区分:绘制位移 ≠ 进度(2026-09-30 真机报障修)
 *
 * 这份数学只产出**进度**,不产出位移。绘制必须用 `slide(travel)`,不要拿进度乘行宽:
 * 进度是"离提交线还有多远",位移是"画面该挪多少"。混用的后果是**放大**——
 * 候选行翻页曾把进度乘整行宽(阈值是行宽 1/3),手指走 1/3 画面走满整行,放大 3 倍,
 * 于是"跟手"变成"手指在前 8% 行宽里画面完全不动,之后画面比手指快 3 倍"。
 * 真机报障是「翻页不跟手」+「翻页动画太短」——后者其实是零动画:
 * 画面在手指松开前就到了位,松手时 `from == target`,直接返回。
 *
 * **跟手的定义:画面位移 = 手指位移**,中间不做任何归一化。
 *
 * ## 死区里也要有响应
 *
 * 死区取固定的 [DEAD_DP](8dp)是为了防误触,但"手指在动、屏幕完全不动"这段静默本身就被感知成卡顿。
 * 所以死区内给 [DEAD_SLIP] 权重的最小响应:不启动拖动,但画面跟着走一点。
 *
 * ## 动画一律非线性
 *
 * 2026-09-30 用户定案「所有动画都使用非线性」。三处补完动画此前都用 `ValueAnimator` 的
 * 默认插值(= 线性),匀速推看着像机器在动;现在统一走 [EASE_OUT](缓出曲线,快进慢停)。
 * 缓动属于**时间**维度,由动画插值器负责,不要在绘制函数里手乘 `s²` —— 那是把时间曲线
 * 混进空间计算,飞字的抬升与淡出都受牵连。
 */
internal object DragGesture {

    /**
     * **手势死区**(dp):**常量值**,横滑与上滑共用,**不随触发阈值变化**
     * (2026-10-02 用户「死区大小不随着触发阈值变化」「左右滑动和上下滑动的死区都是固定大小」
     * 「死区不使用比例计算 采用固定值」「死区改为常量值」)。
     *
     * 此前两处都取 `触发线 × 1/4`,于是死区跟着阈值放大:
     * - 横滑:标准档 59dp / 保守档 81dp —— **手指先走 59dp 屏幕纹丝不动**,
     *   这就是"翻页不跟手"的直接来源(不是没实现,是前面空了一段那么长);
     * - 上滑:12.5 / 20 / 30dp。
     * 阈值本来就有三档,死区再跟着放大三档,于是「灵敏」和「保守」差的不只是触发点,
     * 还有一段完全空白的起手距离 —— 调阈值时手感会连带乱掉。
     *
     * ## 16dp → 8dp(2026-10-02 用户「缩小死区」)
     *
     * 16dp ≈ 一次普通触摸 slop 的两倍,是防误触的保守取值。但那三档**提交距离**换了口径
     * (见 `ImeService.PAGE_THRESHOLD_TIERS`:键盘面那一列改成**死区之外**的提交距离),
     * 于是死区不再偷偷吃掉灵敏度,可以单独往小了调 —— 此前做不到:改死区等于改灵敏度。
     *
     * 8dp = 16 物理 px(@density 2.0),仍大于系统 slop(约 8dp)本身,不至于把"手抖"
     * 判成横滑。死区内仍有 [DEAD_SLIP] 的响应,所以那段不是完全的静默。
     *
     * **不给比例、不给默认值**:`progress`/`slide` 的 `dead` 是**必填参数**,
     * 类型上就不存在"忘了给、按比例算"这条路。死区不单独设开关 ——
     * 它是防误触的量,不是手感偏好,调它的人只会调触发阈值。
     *
     * 这里是**屏幕触摸板**上的那一档(候选行/L5/L6)。**键盘表面用它自己那一档**
     * ([DEAD_DP_SURFACE],更大),理由见那条。
     */
    const val DEAD_DP = 8f

    /**
     * **屏幕触摸板**上横滑(翻页)的死区:**8dp 常量**,与纵向的 [DEAD_DP] 同值、但**是独立常量**
     * (各自是一个可单独调的旋钮;2026-10-04 曾取 `DEAD_DP` 的一半 = 4dp,10-09 改回 8dp)。
     *
     * 用的是**屏幕上的**候选行 / L5 / L6 —— 那边没有"手按在键上"这回事,8dp ≈ 1.3mm
     * 已经够压住触摸板的落点噪声。**键盘表面不吃这个常量**,它有自己的 [DEAD_DP_SURFACE]
     * (12dp;那段 4dp → 8dp → 12dp 的经过与理由都写在那条上)。
     *
     * 灵敏度归**档位表**([dev.hwkbd.ime.service.ImeService] 的 `PAGE_THRESHOLD_TIERS` 第二列,
     * 那是用户真正在调的旋钮),死区只负责「别把抖动当意图」—— 所以它不跟阈值联动、也不走比例。
     */
    const val DEAD_DP_SWIPE = 8f

    /**
     * **键盘表面**(固件映射成屏幕触摸的那块键面)的死区:**12dp 常量**,横纵同值。
     *
     * 2026-10-16 用户:「键盘面死区调大 8dp → 12dp」+「连横滑阈值档位一起调大」。
     *
     * 起因是「死区和按键时的静默窗组合起来还是有很多误触」。键面不是真实触摸屏:
     * 落点由固件按 **10 个键列**映射到屏宽(一列 ≈ 144px @1440 ≈ 9mm),压键那一下手指会滚一下,
     * 表面就报出可观的位移,而这段位移**不是意图**。8dp ≈ 1.3mm 挡不住它。
     *
     * ## 为什么键盘面单独一个常量(而屏幕触摸板仍是 8dp)
     *
     * | 面 | 死区 | 值 | 为什么 |
     * |---|---|---|---|
     * | 屏幕上的候选行 / L5 / L6(真触摸板) | [DEAD_DP] / [DEAD_DP_SWIPE] | 8dp ≈ 1.3mm | 没有按键干扰,落点噪声小 |
     * | 键盘表面(ImeService 的 `FlyDetector`) | 本常量(横纵都用) | 12dp ≈ 1.9mm | 键面是固件映射的,还有"手在键上"这层干扰 |
     *
     * 但它**不负责挡住按键抖动** —— 那件事归静默窗([dev.hwkbd.ime.ime.KeyEventGate]:
     * 按住键期间直接不接手势)。死区只管"手放在键面上、还没打算划"的那点噪声。
     *
     * ## 经过:横滑死区 4dp → 8dp(2026-10-09)→ 12dp(2026-10-16)
     *
     * 4dp 是 2026-10-04 为了「翻页要更灵」定的 —— 那是**灵敏度**的选择,不是**防抖**的选择:
     *
     * ```
     * 4dp × density 2.5(Titan 2 / 400dpi)= 10px ≈ 0.6mm
     * ```
     *
     * **0.6mm 小于生理性手抖**(指尖静止时的震颤约 0.3~1mm),于是「手指放在键盘上」本身
     * 就会跨过它 —— 用户报「没有死区,手指在键盘上的抖动也识别了」。8dp 之后仍报误触,
     * 于是 2026-10-16 键盘面单独走到 12dp。
     *
     * **横纵都用本常量**:键面上的上滑(飞字)与横滑(翻页)是同一种手,不该有两档。
     *
     * ## 键盘面上「真去翻一页」要划多远(2026-10-16 与档位一起调大后)
     *
     * MOVE 里的接管门槛是 `adx > swipeDeadZone`,基线定在**跨过它的那一帧**;
     * 抬手兜底那条线是 `swipeDeadZone + pageThresholdPx`([ImeService.FlyDetector.onMotion])。
     * 两条都落在「死区 + 提交线」这个量级上:
     *
     * | 档位 | 提交线 | 总行程(死区 30px + 提交线) |
     * |---|---|---|
     * | sensitive | 12px | ≈42px ≈ 2.7mm |
     * | normal | 24px | ≈54px ≈ 3.4mm |
     * | conservative | 60px | ≈90px ≈ 5.7mm |
     *
     * 参照:一个键列 ≈ 144px ≈ 9mm —— 最粗档约 0.63 个键列,要划出大半个键距才翻页。
     */
    const val DEAD_DP_SURFACE = 12f

    /**
     * 死区内的**最小响应比例**:手指在死区里移动时,画面跟着走这么比例。
     *
     * 取 1/3 而不是 0:完全不给响应的话,那段静默会被感知成"没跟手";
     * 给一点就足以表明"我收到了",又不至于把防误触的死区架空。
     */
    const val DEAD_SLIP = 0.33f

    /**
     * 跟手进度:位移沿手势正方向累计时,返回 `0..1` 的进度。**只用于判定提交与否。**
     *
     * @param travel 位移(px,已取沿正方向的绝对值)
     * @param threshold 触发阈值(px,走完这一段就触发)
     * @param dead 死区(px),由调用方按 [DEAD_DP] × density 给;**必填**,免得退回比例
     */
    fun progress(travel: Float, threshold: Float, dead: Float): Float {
        if (threshold <= 0f) return if (travel > 0f) 1f else 0f
        return ((travel - dead) / (threshold - dead)).coerceIn(0f, 1f)
    }

    /**
     * **跟手绘制位移**(px):画面该跟着手指挪多少。**绘制只用这个,不要用 [progress]。**
     *
     * 死区内按 [DEAD_SLIP] 打折(仍有响应),出了死区后 1:1 跟手,超过 [limit] 则夹住。
     *
     * @param travel 位移(px,已取沿手势正方向的绝对值)
     * @param limit 位移上限(px)。翻页传行宽——一整页就是画面该走的全部距离。
     * @param dead 死区(px),同 [progress]:[DEAD_DP] × density,**必填**
     */
    fun slide(travel: Float, limit: Float, dead: Float): Float {
        val mag = if (travel <= dead) travel * DEAD_SLIP else travel
        return mag.coerceIn(0f, limit)
    }

    /**
     * 跟手动画的**基准时长**(ms):走完剩余的 `(1-p)` 距离所需时间。
     *
     * ## 只作为物理参数的参照,不再用来算时长(2026-10-02)
     *
     * 旧实现是"剩余距离 × 固定基准时长",靠 [settleDuration] 算实际时长。问题在于:
     * 时长**与松手早晚无关** —— 差 1px 和差半页用同一个时长,而且动画从零初速起步,
     * 于是松手瞬间画面速度从指尖速度掉到 0(「顿一下」),中途被打断又从静止重开
     * (「打断后反向动画」)。两条都是固定时长动画器的结构问题。
     *
     * 现在补完/收回全部走 [SpringChannel](官方 `SpringAnimation`),时长由弹簧按
     * **行程与初速**自己算。340ms 保留在 [SpringSpec.DEFAULT] 的 `response` 里作为
     * **"多久到附近"的调参依据**,保证换引擎前后手感不突变。
     */
    const val SETTLE_MS = 340f
}
