package dev.hwkbd.ime.telemetry

/**
 * 隐私粗化:把要落盘的东西**降级成统计上不可重识别的形状**。
 *
 * ## 「不暴露个人特征」的可判定标准
 *
 * 不是"我们不采集敏感信息"这种自我声明,而是一个能被攻击者验证的问题:
 *
 * > 拿到整份数据,能不能**重识别出某个具体用户或设备**,或定位到它的某一次崩溃?
 *
 * 所以规则是:**数据里不能出现「稀有组合 + 稳定标识」的串联。**
 *
 * ## 去掉与粗化的
 *
 * | 类别 | 处理 | 理由 |
 * | --- | --- | --- |
 * | 签名证书指纹 | **完全不写** | 同一台机器上恒定 ⇒ 就是设备指纹;同时它还是校验逻辑的一半,写出来等于告诉攻击者要改哪里 |
 * | 厂商 + 型号 | **不写** | 指纹的主要来源,而对"哪个 ABI 上崩得多"这个问题毫无分析价值 |
 * | 精确 SDK / 精确 density | **粗桶** | 单个不强,但与时间戳一串就能缩小到个人 |
 * | 输入内容 / 候选词 | **从不采集** | 唯一真正暴露"这个人在做什么"的类别 |
 *
 * 保留的是:粗桶后的 ABI / 系统版本 / 密度档,以及异常栈。
 *
 * ## 崩溃栈要脱敏吗
 *
 * 栈里**不含用户输入** —— 异常栈是代码路径,不是数据。所以原样保留:
 * 脱敏它反而会让定位崩溃变难,那是本末倒置。
 * 唯一的风险是异常 `message` 里带了变量值(例如"找不到词典 /Users/gem/…"),
 * 那属于自己写日志时的疏忽,不是这里能靠脱敏兜住的。
 */
object Redaction {

    /**
     * 系统版本粗桶:**只送主版本**。
     *
     * 精确的 SDK 号与机型、density 一串就是准标识符。
     */
    fun sdkBucket(sdk: Int): String = when {
        sdk >= 35 -> "35+"
        sdk == 34 -> "34"
        sdk == 33 -> "33"
        sdk in 30..32 -> "30-32"
        sdk in 26..29 -> "26-29"
        else -> "<26"
    }

    /** 密度粗桶:只保留整数档,不送精确值。 */
    fun densityBucket(density: Float): String = when {
        density < 1.0f -> "<1"
        density < 1.5f -> "1.0-1.5"
        density < 2.0f -> "1.5-2.0"
        density < 2.5f -> "2.0-2.5"
        density < 3.0f -> "2.5-3.0"
        density < 4.0f -> "3.0-4.0"
        else -> "4+"
    }

    /**
     * 设备粗桶:只送 ABI 家族。
     *
     * 保留 ABI 是因为"哪个目标设备上崩得多"是真问题(Titan 2 是 arm64,
     * 而模拟器是 x86_64,两者的问题不一样);厂商型号没有这个价值。
     */
    fun abiBucket(abis: List<String>): String = when {
        abis.any { it.startsWith("arm64") } -> "arm64-v8a"
        abis.any { it.startsWith("armeabi") } -> "armeabi-v7a"
        abis.any { it.startsWith("x86_64") } -> "x86_64"
        abis.any { it.startsWith("x86") } -> "x86"
        else -> "other"
    }

    /**
     * 文件名里的时间戳会不会成为标识符?
     *
     * 不会自己成为,但**分钟级精度 + 稀有机型**的组合可能。所以文件名只保留到分钟,
     * 且不上传(本地文件)。这一条写在这里是为了说明:文件名不做哈希是有意的 ——
     * 你要能按时间排序看,哈希掉了就没法看了。
     */
    const val FILENAME_TIMESTAMP = "yyyy-MM-dd'T'HH-mm"
}
